export function generarSillas(idBus: number): Silla[] {
  return Array.from({ length: 20 }, (_, i) => ({
    id_silla: idBus * 100 + i + 1,
    id_bus: idBus,
    numero: i + 1,
    ubicacion: i % 2 === 0 ? 'VENTANA' : 'PASILLO',
  }));
}

